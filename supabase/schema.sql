create table if not exists public.rh_posts (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity (start with 1) unique,
  user_id uuid references auth.users(id) on delete set null,
  author_label text not null,
  title text not null,
  body text not null,
  tags text[] not null default '{}'::text[],
  duration text not null,
  images text[] not null,
  votes_count integer not null default 0 check (votes_count >= 0),
  comments_count integer not null default 0 check (comments_count >= 0),
  status text not null default 'pending',
  review_note text,
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  is_hidden boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint rh_posts_title_len check (char_length(btrim(title)) between 4 and 32),
  constraint rh_posts_body_len check (char_length(btrim(body)) between 10 and 300),
  constraint rh_posts_tags_len check (cardinality(tags) between 1 and 5),
  constraint rh_posts_duration_len check (char_length(btrim(duration)) between 1 and 24),
  constraint rh_posts_images_len check (cardinality(images) between 1 and 6),
  constraint rh_posts_status_check check (status in ('pending', 'approved', 'rejected'))
);

-- Upgrade an existing installation.
alter table public.rh_posts
  add column if not exists status text not null default 'pending',
  add column if not exists review_note text,
  add column if not exists reviewed_at timestamptz,
  add column if not exists reviewed_by uuid references auth.users(id) on delete set null,
  add column if not exists updated_at timestamptz not null default now();

update public.rh_posts
set status = 'pending'
where status is null;

update public.rh_posts
set updated_at = created_at
where updated_at is null;

alter table public.rh_posts
  drop constraint if exists rh_posts_status_check;

alter table public.rh_posts
  add constraint rh_posts_status_check
  check (status in ('pending', 'approved', 'rejected'));

-- The request explicitly removes the sample rooms.
delete from public.rh_posts
where user_id is null;

create index if not exists rh_posts_public_created_idx
  on public.rh_posts (status, is_hidden, created_at desc);

