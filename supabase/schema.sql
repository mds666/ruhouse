create or replace function public.rh_cast_vote(p_post_id uuid)
returns table (votes_count integer, has_voted boolean)
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_inserted integer := 0;
  v_count integer;
begin
  if v_user is null then
    raise exception '请先完成匿名身份初始化。' using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.rh_posts p
    where p.id = p_post_id
      and p.status = 'approved'
      and p.is_hidden = false
  ) then
    raise exception '这条房间记录不存在或还在审核中。' using errcode = 'P0002';
  end if;

  insert into public.rh_votes (post_id, user_id)
  values (p_post_id, v_user)
  on conflict (post_id, user_id) do nothing;

  get diagnostics v_inserted = row_count;

  if v_inserted > 0 then
    update public.rh_posts as p
      set votes_count = p.votes_count + 1
      where p.id = p_post_id
      returning p.votes_count into v_count;
  else
    select p.votes_count into v_count
    from public.rh_posts p
    where p.id = p_post_id;
  end if;

  return query select coalesce(v_count, 0), true;
end;
$$;

create or replace function public.rh_add_comment(p_post_id uuid, p_content text)
returns table (
  id uuid,
  author_label text,
  content text,
  created_at timestamptz,
  is_mine boolean,
  comments_count integer
)
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_content text := btrim(coalesce(p_content, ''));
  v_id uuid;
  v_created_at timestamptz;
  v_count integer;
  v_author text;
begin
  if v_user is null then
    raise exception '请先完成匿名身份初始化。' using errcode = '42501';
  end if;

  if char_length(v_content) < 2 or char_length(v_content) > 160 then
    raise exception '评论需要 2—160 个字符。' using errcode = '22023';
  end if;

  if v_content ~ '1[3-9][0-9]{9}'
     or v_content ~* '[0-9]{17}[0-9x]' then
    raise exception '评论里疑似包含手机号或身份证号，请删除后再发布。' using errcode = '22023';
  end if;

  if not exists (
    select 1 from public.rh_posts p
    where p.id = p_post_id
      and p.status = 'approved'
      and p.is_hidden = false
  ) then
    raise exception '这条房间记录不存在或还在审核中。' using errcode = 'P0002';
  end if;

  v_author := public.rh_author_label(v_user);

  insert into public.rh_comments (post_id, user_id, author_label, content)
  values (p_post_id, v_user, v_author, v_content)
  returning public.rh_comments.id, public.rh_comments.created_at
  into v_id, v_created_at;

  update public.rh_posts as p
    set comments_count = p.comments_count + 1
    where p.id = p_post_id
    returning p.comments_count into v_count;

  return query select v_id, v_author, v_content, v_created_at, true, coalesce(v_count, 0);
end;
$$;

