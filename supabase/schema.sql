  end if;

  if char_length(v_title) < 4 or char_length(v_title) > 32 then
    raise exception '标题需要 4—32 个字符。' using errcode = '22023';
  end if;

  if char_length(v_body) < 10 or char_length(v_body) > 300 then
    raise exception '正文需要 10—300 个字符。' using errcode = '22023';
  end if;

  if cardinality(v_tags) < 1 or cardinality(v_tags) > 5 then
    raise exception '请选择 1—5 个标签。' using errcode = '22023';
  end if;

  if exists (
    select 1
    from unnest(v_tags) as t(tag)
    where t.tag is null
      or char_length(btrim(t.tag)) < 1
      or char_length(btrim(t.tag)) > 12
  ) then
    raise exception '标签长度不合法。' using errcode = '22023';
  end if;

  if char_length(v_duration) < 1 or char_length(v_duration) > 24 then
    raise exception '入住时长不合法。' using errcode = '22023';
  end if;

  if cardinality(v_images) < 1 or cardinality(v_images) > 6 then
    raise exception '请上传 1—6 张房间照片。' using errcode = '22023';
  end if;

  foreach v_image in array v_images loop
    if v_image is null
       or v_image !~ ('^rooms/' || v_user::text || '/[A-Za-z0-9._-]+$') then
      raise exception '图片路径不合法。' using errcode = '22023';
    end if;
  end loop;

  if v_title ~ '1[3-9][0-9]{9}'
     or v_body ~ '1[3-9][0-9]{9}'
     or v_title ~* '[0-9]{17}[0-9x]'
     or v_body ~* '[0-9]{17}[0-9x]' then
    raise exception '文字里疑似包含手机号或身份证号，请删除后再发布。' using errcode = '22023';
  end if;

  select array_agg(btrim(t.tag) order by t.ord)
    into v_tags
  from unnest(v_tags) with ordinality as t(tag, ord);

  update public.rh_posts as p
  set title = v_title,
      body = v_body,
      tags = v_tags,
      duration = v_duration,
      images = v_images,
      status = 'pending',
      review_note = null,
      reviewed_at = null,
      reviewed_by = null
  where p.id = p_post_id
    and p.user_id = v_user
    and p.is_hidden = false
  returning p.id, p.status, p.updated_at
  into v_id, v_status, v_updated_at;

  if v_id is null then
    raise exception '这条房间记录不存在。' using errcode = 'P0002';
  end if;

  return query select v_id, v_status, v_updated_at;
end;
$$;

