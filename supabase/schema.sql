-- ============================================================
-- Rubbish House / 垃圾房子
-- Supabase schema + moderation upgrade
--
-- Run this file in the Supabase SQL Editor. It is safe to re-run.
--
-- What it does:
--   1. Creates/updates posts, votes, comments, admins
--   2. Adds the review workflow (pending / approved / rejected)
--   3. Removes the old demo posts (user_id IS NULL)
--   4. Creates the room-photos Storage bucket + policies
--   5. Exposes only the functions the website needs
--
-- After running this file:
--   - Create an admin Auth user in Authentication → Users
--   - Run add-admin.sql (or the SQL at the bottom of this file)
-- ============================================================

