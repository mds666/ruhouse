create or replace function public.rh_author_label(p_user uuid)
returns text
language plpgsql
immutable
set search_path = public, pg_temp
as $$
declare
  v_number integer;
begin
  if p_user is null then
    return '匿名租客';
  end if;

  v_number := (abs(hashtext(p_user::text)::bigint) % 900 + 100)::integer;
  return '匿名租客 #R-' || lpad(v_number::text, 3, '0');
end;
$$;

