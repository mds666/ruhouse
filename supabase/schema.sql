    p.id,
    p.number,
    p.title,
    p.body,
    p.tags,
    p.duration,
    p.author_label,
    p.votes_count,
    p.comments_count,
    p.images,
    p.status,
    p.review_note,
    p.created_at,
    p.updated_at
  from public.rh_posts p
  where p.is_hidden = false
    and (p_status is null or p.status = p_status)
  order by
    case p.status
      when 'pending' then 0
      when 'rejected' then 1
      else 2
    end,
    p.updated_at desc
  limit 200;
end;
$$;

create or replace function public.rh_admin_stats()
returns table (pending integer, approved integer, rejected integer)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.rh_is_admin() then
    raise exception '需要管理员权限。' using errcode = '42501';
  end if;

  return query
  select
    count(*) filter (where p.status = 'pending')::integer,
    count(*) filter (where p.status = 'approved')::integer,
    count(*) filter (where p.status = 'rejected')::integer
  from public.rh_posts p
  where p.is_hidden = false;
end;
$$;

create or replace function public.rh_admin_review_post(
  p_post_id uuid,
  p_status text,
  p_note text default null
)
returns table (id uuid, status text, review_note text, updated_at timestamptz)
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_admin uuid := auth.uid();
  v_note text := btrim(coalesce(p_note, ''));
begin
  if not public.rh_is_admin() then
    raise exception '需要管理员权限。' using errcode = '42501';
  end if;

  if p_status is null or p_status not in ('approved', 'rejected') then
    raise exception '只能通过或拒绝。' using errcode = '22023';
  end if;

  if p_status = 'rejected' and (char_length(v_note) < 2 or char_length(v_note) > 200) then
    raise exception '拒绝时请填写 2—200 字的审核说明。' using errcode = '22023';
  end if;

  if p_status = 'approved' then
    v_note := null;
  end if;

  update public.rh_posts as p
  set status = p_status,
      review_note = v_note,
      reviewed_at = now(),
      reviewed_by = v_admin
  where p.id = p_post_id
    and p.is_hidden = false;

  if not found then
    raise exception '这条房间记录不存在。' using errcode = 'P0002';
  end if;

  return query
  select p.id, p.status, p.review_note, p.updated_at
  from public.rh_posts p
  where p.id = p_post_id;
end;
$$;

